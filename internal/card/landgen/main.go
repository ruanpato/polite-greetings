// Command landgen writes internal/card/land.go: points on land, about 3.6°
// apart and spread over nearly equal areas, for the dotted globe of the cosmos
// layout.
//
// The input is Natural Earth's 1:110m land polygons, which are in the public
// domain. The committed land.go was made from this file (SHA-256 9e0729ee…35d9):
//
//	curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/693f11422f4e08d2da4566b854dda53eb7c39fb3/geojson/ne_110m_land.geojson
//	go run ./internal/card/landgen ne_110m_land.geojson > internal/card/land.go
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"math"
	"os"
)

// step is the spacing of the points, in degrees of latitude.
const step = 3.6

type polygon [][][2]float64 // rings of [longitude, latitude]

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: landgen ne_110m_land.geojson > land.go")
		os.Exit(2)
	}
	polygons, err := load(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./internal/card/landgen; DO NOT EDIT.\n\n")
	b.WriteString("package card\n\n")
	b.WriteString("// land lists points on land in tenths of a degree, latitude first, sampled\n")
	b.WriteString(fmt.Sprintf("// every %.1f° over nearly equal areas from Natural Earth's 1:110m land polygons.\n", step))
	b.WriteString("var land = [...][2]int16{\n")
	n := 0
	for row := 0; ; row++ {
		lat := -90 + step/2 + float64(row)*step
		if lat >= 90 {
			break
		}
		count := max(1, int(math.Round(360*math.Cos(lat*math.Pi/180)/step)))
		for i := range count {
			lon := -180 + (float64(i)+0.5)*360/float64(count)
			if onLand(polygons, lon, lat) {
				fmt.Fprintf(&b, "{%d, %d},", int(math.Round(lat*10)), int(math.Round(lon*10)))
				n++
				if n%8 == 0 {
					b.WriteString("\n")
				}
			}
		}
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.Write(src)
	fmt.Fprintf(os.Stderr, "%d points on land\n", n)
}

func load(path string) ([]polygon, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var fc struct {
		Features []struct {
			Geometry struct {
				Type        string          `json:"type"`
				Coordinates json.RawMessage `json:"coordinates"`
			} `json:"geometry"`
		} `json:"features"`
	}
	if err := json.Unmarshal(data, &fc); err != nil {
		return nil, err
	}
	var out []polygon
	for _, f := range fc.Features {
		switch f.Geometry.Type {
		case "Polygon":
			var p polygon
			if err := json.Unmarshal(f.Geometry.Coordinates, &p); err != nil {
				return nil, err
			}
			out = append(out, p)
		case "MultiPolygon":
			var ps []polygon
			if err := json.Unmarshal(f.Geometry.Coordinates, &ps); err != nil {
				return nil, err
			}
			out = append(out, ps...)
		default:
			return nil, fmt.Errorf("unexpected geometry %q", f.Geometry.Type)
		}
	}
	return out, nil
}

// onLand reports whether the point is inside any polygon, holes included
// (even-odd rule over all rings of a polygon).
func onLand(polygons []polygon, lon, lat float64) bool {
	for _, p := range polygons {
		inside := false
		for _, ring := range p {
			if inRing(ring, lon, lat) {
				inside = !inside
			}
		}
		if inside {
			return true
		}
	}
	return false
}

func inRing(ring [][2]float64, x, y float64) bool {
	inside := false
	for i, j := 0, len(ring)-1; i < len(ring); j, i = i, i+1 {
		xi, yi, xj, yj := ring[i][0], ring[i][1], ring[j][0], ring[j][1]
		if (yi > y) != (yj > y) && x < (xj-xi)*(y-yi)/(yj-yi)+xi {
			inside = !inside
		}
	}
	return inside
}
